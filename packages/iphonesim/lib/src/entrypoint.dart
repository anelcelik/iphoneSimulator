import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import 'generated/shell_bundle.g.dart';
import 'project.dart';
import 'version.dart';

/// Settings written into the generated entrypoint.
class SimulatorOptions {
  const SimulatorOptions({
    required this.device,
    this.lenientPlugins = true,
    this.iosFromStart = false,
    this.screenshotDir,
  });

  final String device;
  final bool lenientPlugins;
  final bool iosFromStart;
  final String? screenshotDir;
}

/// Writes build/iphonesim/: the shell sources and a main.dart that runs the
/// app's own main() inside the simulator. Returns the entrypoint path.
///
/// Nothing outside build/ is touched, and build/ is in every Flutter
/// project's .gitignore.
String writeSimulatorFiles(FlutterProject project, String target, SimulatorOptions options) {
  final appImport = project.importFor(target);
  final shellDir = Directory(p.join(project.buildDir, 'shell'));
  if (shellDir.existsSync()) shellDir.deleteSync(recursive: true);
  shellBundle.forEach((relative, encoded) {
    final file = File(p.join(shellDir.path, relative));
    file.parent.createSync(recursive: true);
    file.writeAsStringSync('$copiedFileHeader${utf8.decode(base64.decode(encoded))}');
  });

  final entrypoint = File(p.join(project.buildDir, 'main.dart'));
  entrypoint.writeAsStringSync(renderEntrypoint(
    appImport: appImport,
    appName: project.name,
    stateFile: p.join(project.buildDir, 'state.json'),
    options: options,
  ));
  return entrypoint.path;
}

const String copiedFileHeader = '// Copied by iphonesim $packageVersion. Do not edit: overwritten on every run.\n'
    '// ignore_for_file: type=lint\n';

String renderEntrypoint({
  required String appImport,
  required String appName,
  required String stateFile,
  required SimulatorOptions options,
}) {
  final screenshotDir = options.screenshotDir;
  return '''
// Generated by iphonesim $packageVersion on every run. Do not edit.
// ignore_for_file: type=lint

import ${_literal(appImport)} as app;

import 'shell/iphonesim_shell.dart' as sim;

void main() {
  sim.runSimulated(
    app.main,
    const sim.SimulatorConfig(
      device: ${_literal(options.device)},
      lenientPlugins: ${options.lenientPlugins},
      iosFromStart: ${options.iosFromStart},
      appName: ${_literal(appName)},
      stateFile: ${_literal(stateFile)},
      screenshotDir: ${screenshotDir == null ? 'null' : _literal(screenshotDir)},
    ),
  );
}
''';
}

/// A Dart string literal for [value]: JSON escaping plus `$`.
String _literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
